package `in`.campusone.app.util

import android.content.Context
import android.graphics.pdf.PdfDocument
import android.os.Environment
import androidx.core.content.ContextCompat
import `in`.campusone.app.domain.model.UserProfile
import `in`.campusone.app.domain.usecase.GpaCalculationResult
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import kotlin.Result

const val MAX_FILE_SIZE_BYTES: Long = 10_000_000L // 10 MB free-tier guard
const val COMPRESSED_IMAGE_MAX_BYTES: Long = 600_000L // 600 KB for images

object StudyFileAndPdfHelper {

    /** Validates that a file upload stays within the 10 MB free-tier limit. */
    fun validateFileSize(fileSizeBytes: Long): kotlin.Result<Unit> =
        if (fileSizeBytes <= MAX_FILE_SIZE_BYTES) {
            kotlin.Result.success(Unit)
        } else {
            kotlin.Result.failure(IllegalStateException("File exceeds 10 MB limit. Please compress or pick a smaller file."))
        }

    /**
     * Exports a printable GPA / CGPA grade sheet PDF to the app's external Documents folder.
     * Requires WRITE_EXTERNAL_STORAGE at runtime on pre-Android 10; scoped storage otherwise.
     */
    fun exportGpaReportToPdf(
        context: Context,
        profile: UserProfile,
        result: GpaCalculationResult
    ): kotlin.Result<File> = try {
        val documentsDir = context.getExternalFilesDir(Environment.DIRECTORY_DOCUMENTS)
            ?: context.filesDir
        documentsDir.mkdirs()

        val fileName = "CampusOne_GradeSheet_Sem${profile.semester}_${SimpleDateFormat("yyyyMMdd_HHmm", Locale.getDefault()).format(Date())}.pdf"
        val pdfFile = File(documentsDir, fileName)

        val document = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(612, 792, 1).create()
        val page = document.startPage(pageInfo)
        val canvas = page.canvas

        val paint = android.graphics.Paint()
        paint.color = ContextCompat.getColor(context, android.R.color.black)
        paint.textSize = 18f
        paint.isAntiAlias = true

        var y = 60f
        canvas.drawText("CampusOne — Grade Sheet", 60f, y, paint)
        y += 40f
        paint.textSize = 14f
        canvas.drawText("Student: ${profile.name.ifBlank { "HNBGU Student" }}", 60f, y, paint)
        y += 24f
        canvas.drawText("College: ${profile.collegeName.ifBlank { "HNB Garhwal University" }}", 60f, y, paint)
        y += 24f
        canvas.drawText("Course: ${profile.courseName.ifBlank { "B.Sc. Computer Science" }} • Sem ${profile.semester} • Sec ${profile.section}", 60f, y, paint)
        y += 24f
        canvas.drawText("Grading Scale: ${result.scaleType.label}", 60f, y, paint)
        y += 36f

        paint.textSize = 16f
        paint.isFakeBoldText = true
        canvas.drawText("Semester SGPA: ${result.formattedSgpa}", 60f, y, paint)
        paint.isFakeBoldText = false
        y += 28f
        canvas.drawText("Cumulative CGPA: ${result.formattedCgpa}", 60f, y, paint)
        y += 28f
        canvas.drawText("Equivalent Percentage: ${result.formattedPercentage}", 60f, y, paint)
        y += 28f
        canvas.drawText("Total Credits: ${result.totalCredits}", 60f, y, paint)
        y += 40f

        paint.textSize = 14f
        paint.isFakeBoldText = true
        canvas.drawText("Current Semester Subjects", 60f, y, paint)
        paint.isFakeBoldText = false
        y += 26f

        for (course in result.semesterTrend.lastOrNull()?.courses.orEmpty()) {
            canvas.drawText(
                "${course.subjectCode} • ${course.subjectName} • ${course.credits} cr • Grade ${String.format(Locale.US, "%.2f", course.gradePoint)}",
                60f, y, paint
            )
            y += 24f
            if (y > 740f) {
                document.finishPage(page)
                val newPage = document.startPage(pageInfo)
                document.writeTo(FileOutputStream(pdfFile))
                page.canvas.drawText("(continued)", 60f, 40f, paint)
                y = 60f
            }
        }

        y += 16f
        paint.textSize = 12f
        paint.color = ContextCompat.getColor(context, android.R.color.darker_gray)
        canvas.drawText("Generated by CampusOne — Offline-First • MIT Open Source • ${SimpleDateFormat("dd MMM yyyy, hh:mm a", Locale.getDefault()).format(Date())}", 60f, y, paint)

        document.finishPage(page)
        document.writeTo(FileOutputStream(pdfFile))
        document.close()

        kotlin.Result.success(pdfFile)
    } catch (e: Exception) {
        kotlin.Result.failure(e)
    }
}
